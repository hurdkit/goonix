#!/usr/bin/env bash
# Regression for the committed runners' job isolation (reviewer, 2026-11-23).
#
# WHAT IT PROVES.  Each runner that starts a namespace daemon must enter a
# private PID namespace INSIDE the UID/GID mapping boundary, and its part
# script must REFUSE to start the daemon outside one.  Without that, the
# daemon's build-user cleanup kill(-1, SIGKILL) reaches every process of the
# leased uid on the HOST - measured killing another job's builders (goonix
# DECISIONS 30).
#
# This is a MUTATION test, not a smoke test: it runs the real handshake twice,
# once as committed (must pass, PID 1) and once with the isolation line reverted
# to 'exec bash' (must FAIL the check).  A check that passes in both cases proves
# nothing, so the reverted case failing is the point.
#
# No daemon, no build, no store writes: the part script here is only the check.
# Safe to run beside other jobs.
set -uo pipefail

host_uid=$(id -u)
host_gid=$(id -g)
read -r sub_uid sub_uid_count < <(awk -F: -v u="$USER" '$1==u{print $2,$3}' /etc/subuid)
read -r sub_gid sub_gid_count < <(awk -F: -v u="$USER" '$1==u{print $2,$3}' /etc/subgid)
if [ -z "${sub_uid:-}" ] || [ -z "${sub_gid:-}" ]; then
  echo 'SKIP: no subordinate id ranges for this user' >&2
  exit 0
fi
# The SETUID wrappers, exactly as the committed runners require.
if [ -x /run/wrappers/bin/newuidmap ]; then export PATH=/run/wrappers/bin:$PATH; fi
command -v newuidmap >/dev/null || { echo 'FAIL: newuidmap not on PATH' >&2; exit 1; }

work=$(mktemp -d /tmp/pid-ns-check.XXXXXX)
trap 'rm -rf "$work"' EXIT

# The check, copied from the committed part scripts.  Kept in sync by the
# grep assertion at the bottom of this file.
cat > "$work/part.sh" <<'PART'
set -uo pipefail
echo "PID_NS_CHECK pid=$$ ns=$(readlink /proc/self/ns/pid)"
if [ "$$" != 1 ]; then
  echo "REFUSING: not PID 1 of a private PID namespace (pid=$$);" \
       "the runner must exec unshare --pid --fork --kill-child after the maps" >&2
  exit 1
fi
echo 'ISOLATED OK'
PART

# run_case LABEL EXEC_LINE -> prints the case result, returns the part's status.
run_case() {
  local label=$1 exec_line=$2
  rm -f "$work/ns-pid" "$work/ns-go"
  # The committed park-and-map handshake, with only the exec line varying.
  unshare --user --mount bash -c '
    echo "$$" > "$1"
    for i in $(seq 1 600); do [ -e "$2" ] && break; sleep .1; done
    [ -e "$2" ] || { echo "no maps go-ahead" >&2; exit 1; }
    '"$exec_line"'
  ' _ "$work/ns-pid" "$work/ns-go" "$work/part.sh" > "$work/$label.log" 2>&1 &
  local job=$! pid=''
  for i in $(seq 1 300); do
    pid=$(cat "$work/ns-pid" 2>/dev/null | head -1 || true)
    [ -n "$pid" ] && break
    sleep .1
  done
  if [ -z "$pid" ]; then
    echo "$label: FAIL namespace child did not start"
    cat "$work/$label.log"
    return 1
  fi
  newuidmap "$pid" 0 "$host_uid" 1 1 "$sub_uid" "$sub_uid_count" || return 1
  newgidmap "$pid" 0 "$host_gid" 1 1 "$sub_gid" "$sub_gid_count" || return 1
  : > "$work/ns-go"
  wait "$job"
  local rc=$?
  echo "$label: rc=$rc $(grep -h 'PID_NS_CHECK' "$work/$label.log" | head -1)"
  return $rc
}

fails=0

# 1. As committed: the isolation line is present, so the part must be PID 1.
if run_case isolated 'exec unshare --pid --fork --kill-child -- bash "$3"'; then
  echo 'PASS isolated: part script is PID 1 of its own PID namespace'
else
  echo 'FAIL isolated: the committed handshake did not yield PID 1'
  fails=$((fails + 1))
fi

# 2. MUTATION: revert the line.  The check MUST refuse (non-zero).
if run_case reverted 'exec bash "$3"'; then
  echo 'FAIL reverted: the check passed WITHOUT isolation - it proves nothing'
  fails=$((fails + 1))
else
  echo 'PASS reverted: the check refuses to run outside a private PID namespace'
fi

# 3. The committed runners must actually carry both halves.  A runner could
#    pass the cases above and still not be the code that runs in the gate.
here=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
for r in "$here/run.sh" "$here/../goonix-ca8/ca8-core-run.sh"; do
  name=$(basename "$(dirname "$r")")/$(basename "$r")
  if grep -q 'exec unshare --pid --fork --kill-child -- bash "\$3"' "$r"; then
    echo "PASS $name carries the isolation exec line"
  else
    echo "FAIL $name is missing the isolation exec line"
    fails=$((fails + 1))
  fi
  # The part script is generated by a heredoc, so its "$$" appears in the
  # runner ESCAPED as \$\$ - match that literal text, not the runtime form.
  if grep -q 'PID_NS_CHECK pid=' "$r" && grep -qF 'if [ "\$\$" != 1 ]; then' "$r"; then
    echo "PASS $name refuses to start the daemon outside a PID namespace"
  else
    echo "FAIL $name is missing the PID-namespace refusal"
    fails=$((fails + 1))
  fi
done

if [ "$fails" = 0 ]; then
  echo 'PID_NS_REGRESSION PASS'
  exit 0
fi
echo "PID_NS_REGRESSION FAIL ($fails)"
exit 1